#include "musacad_dwg_ac1018_curve.h"
#include <assert.h>
#include <stdint.h>
#include <string.h>
/* Independently synthesized test vectors: no user drawing bytes. */
static const uint8_t circle_2d[] = {
    0x27,0x00,0x44,0x89,0x80,0x40,0x00,0x00,0x81,0x26,0xa1,0x74,
    0x21,0xd0,0x00,0x00,0x00,0x00,0x00,0x00,0x09,0x00,0x00,0x00,
    0x00,0x00,0x00,0x00,0x21,0xc0,0x80,0x00,0x00,0x00,0x00,0x00,
    0x01,0xb4,0x0d,0x48,0x04,0xed,0xa7,
};
static const uint8_t arc_3d[] = {
    0x41,0x00,0x44,0x7c,0x80,0x40,0x00,0x00,0x84,0x8d,0x21,0x74,
    0x21,0xd0,0x00,0x00,0x00,0x00,0x00,0x00,0x31,0x02,0x00,0x00,
    0x00,0x00,0x00,0x20,0x07,0x30,0x00,0x00,0x00,0x00,0x00,0x00,
    0x0f,0x43,0xf0,0x00,0x00,0x00,0x00,0x00,0x01,0xc0,0x7e,0x98,
    0x00,0x00,0x00,0x00,0x00,0x00,0xd0,0x3f,0x00,0x00,0x00,0x00,
    0x00,0x00,0x05,0x90,0x14,0x80,0x40,0x08,0x56,
};
int main(void) {
    MusaDwgAc1018Curve circle={0}, arc={0};
    assert(musa_dwg_ac1018_read_curve_record(circle_2d,sizeof(circle_2d),0u,0x49au,&circle));
    assert(circle.type_code==18u && circle.handle==0x49au);
    assert(circle.center[0]==2.25 && circle.center[1]==-8.5 && circle.center[2]==0.0);
    assert(circle.radius==6.75 && circle.thickness==0.0 && circle.extrusion[2]==1.0);
    assert(musa_dwg_ac1018_read_curve_record(arc_3d,sizeof(arc_3d),0u,0x1234u,&arc));
    assert(arc.type_code==17u && arc.handle==0x1234u);
    assert(arc.center[0]==3.5 && arc.center[1]==0.0 && arc.center[2]==-7.125);
    assert(arc.radius==1.25 && arc.thickness==0.5);
    assert(arc.extrusion[0]==0.0 && arc.extrusion[1]==1.0 && arc.extrusion[2]==0.0);
    assert(arc.start_angle==0.25 && arc.end_angle==5.5);
    MusaDwgAc1018Curve unchanged=arc;
    uint8_t mutated[sizeof(arc_3d)];
    memcpy(mutated,arc_3d,sizeof(mutated));
    mutated[18]^=0x01u;
    assert(!musa_dwg_ac1018_read_curve_record(mutated,sizeof(mutated),0u,0x1234u,&arc));
    assert(!musa_dwg_ac1018_read_curve_record(arc_3d,sizeof(arc_3d),0u,0x1235u,&arc));
    assert(!musa_dwg_ac1018_read_curve_record(arc_3d,sizeof(arc_3d)-1u,0u,0x1234u,&arc));
    assert(!musa_dwg_ac1018_read_curve_record(arc_3d,sizeof(arc_3d),sizeof(arc_3d),0x1234u,&arc));
    assert(memcmp(&arc,&unchanged,sizeof(arc))==0);
    return 0;
}
