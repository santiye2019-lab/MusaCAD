int main(void) {
    MusaDwgAc1018Line line={0};
    MusaDwgAc1018Curve circle={0},arc={0};
    assert(musa_dwg_ac1018_read_line_record(line_eed,sizeof(line_eed),0,0x70fu,&line));
    assert(line.eed_raw_bytes_skipped==19u && fabs(line.start[0]+17.75)<1e-9 &&
           fabs(line.end[2]-3.5)<1e-9);
    assert(musa_dwg_ac1018_read_curve_record(circle_eed,sizeof(circle_eed),0,0x49au,&circle));
    assert(circle.eed_raw_bytes_skipped==19u && circle.radius==6.75 && circle.center[0]==2.25);
    assert(musa_dwg_ac1018_read_curve_record(arc_eed,sizeof(arc_eed),0,0x1234u,&arc));
    assert(arc.eed_raw_bytes_skipped==19u && arc.radius==1.25 && arc.start_angle==0.25);
    MusaDwgAc1018Line before=line;
    uint8_t corrupted[sizeof(line_eed)];
    memcpy(corrupted,line_eed,sizeof(corrupted));
    corrupted[17]^=1u;
    assert(!musa_dwg_ac1018_read_line_record(corrupted,sizeof(corrupted),0,0x70fu,&line));
    assert(!memcmp(&line,&before,sizeof(line)));
    /* EED scanner itself is transactional even on a truncated input. */
    const uint8_t truncated[]={0x44,0x51,0x42};
    MusaDwgAc1015Bits bits={0};
    uint32_t skipped=42u;
    assert(musa_dwg_ac1015_bits_init(&bits,truncated,sizeof(truncated),0u,24u));
    assert(!musa_dwg_ac1018_eed_skip(&bits,&skipped));
    assert(bits.bit_pos==0u && skipped==42u);
    return 0;
}
